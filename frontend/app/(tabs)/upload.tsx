function showError(message: string) {
  if (Platform.OS === "web") {
    window.alert(message);
    return;
  }

  Alert.alert("Upload failed", message);
}

function BasketballUpload() {
  const { user } = useAuth();
  const userId = formatUserId(user?.sub);
  const { value: latestSessionId } = useDatabaseLiveValue<string>(
    `users/${userId}/analysis/activeSessionId`,
  );

  const [isSubmitting, setIsSubmitting] = useState(false);
  const [statusMessage, setStatusMessage] = useState<string | null>(null);
  const [selectedFileName, setSelectedFileName] = useState<string | null>(null);

  const handleUpload = async () => {
    setStatusMessage(null);

    const permission =
      await ImagePicker.requestMediaLibraryPermissionsAsync();

    if (!permission.granted) {
      showError("Media library access is required to pick a shot video.");
      return;
    }

    const pickerResult = await ImagePicker.launchImageLibraryAsync({
      mediaTypes: ["videos"],
      quality: 1,
      allowsEditing: false,
      selectionLimit: 1,
    });

    if (pickerResult.canceled) {
      return;
    }

    const asset = pickerResult.assets[0];

    if (!asset || asset.type !== "video") {
      showError("Please choose a video file to analyze.");
      return;
    }

    setSelectedFileName(asset.fileName ?? "Selected shot video");
    setIsSubmitting(true);

    try {
      setStatusMessage("Uploading your shot to KinetiQ...");
      const analysis = await analyzeVideo(asset);

      setStatusMessage("Saving your results to Firebase...");
      const session = await saveAnalysisSession({
        userId,
        asset,
        analysis,
      });

      router.push({
        pathname: "/shot-breakdown",
        params: { sessionId: session.id },
      });
    } catch (error) {
      const message =
        error instanceof Error
          ? error.message
          : "Something went wrong while analyzing your shot.";
      setStatusMessage(null);
      showError(message);
    } finally {
      setIsSubmitting(false);
    }
  };

  return (
    <ScrollView
      style={styles.scroll}
      contentContainerStyle={styles.scrollContent}
      showsVerticalScrollIndicator={false}
    >
      <View style={styles.card}>
        <View style={styles.dropZone}>
          <View style={styles.iconCircle}>
            {isSubmitting ? (
              <ActivityIndicator color={PURPLE} size="large" />
            ) : (
              <MaterialIcons name="videocam" size={34} color={PURPLE} />
            )}
          </View>
          <Text style={styles.chooseTitle}>Choose video</Text>
          <Text style={styles.chooseSub}>
            Upload a real shot clip and get backend-generated analysis
          </Text>

          <TouchableOpacity
            style={[styles.selectBtn, isSubmitting && styles.selectBtnDisabled]}
            activeOpacity={0.85}
            onPress={handleUpload}
            disabled={isSubmitting}
          >
            <MaterialIcons
              name={isSubmitting ? "sync" : "upload"}
              size={20}
              color="#fff"
            />
            <Text style={styles.selectBtnText}>
              {isSubmitting ? "Analyzing..." : "Select File"}
            </Text>
          </TouchableOpacity>

          {selectedFileName ? (
            <Text style={styles.fileName}>{selectedFileName}</Text>
          ) : null}

          {statusMessage ? (
            <Text style={styles.statusMessage}>{statusMessage}</Text>
          ) : null}
        </View>

        <View style={styles.reqCard}>
          <Text style={styles.reqTitle}>Video Requirements</Text>
          {REQUIREMENTS.map((item) => (
            <View key={item} style={styles.reqRow}>
              <Text style={styles.reqBullet}>•</Text>
              <Text style={styles.reqText}>{item}</Text>
            </View>
          ))}
        </View>

        <View style={styles.infoSection}>
          {FILE_INFO.map((item) => (
            <View key={item} style={styles.infoRow}>
              <Text style={styles.infoBullet}>•</Text>
              <Text style={styles.infoText}>{item}</Text>
            </View>
          ))}
        </View>

        {latestSessionId ? (
          <TouchableOpacity
            style={styles.latestSessionButton}
            activeOpacity={0.85}
            onPress={() =>
              router.push({
                pathname: "/shot-breakdown",
                params: { sessionId: latestSessionId },
              })
            }
          >
            <MaterialIcons name="history" size={18} color={SUCCESS} />
            <Text style={styles.latestSessionText}>Open latest saved analysis</Text>
          </TouchableOpacity>
        ) : null}
      </View>
    </ScrollView>
  );
}

